#define OTA_LAYOUT_ACTIVE_END 0xAFF000u
#define OTA_LAYOUT_AGENT 0x1F00000u
#define OTA_LAYOUT_AGENT_SIZE 0x100000u
#else
#define OTA_LAYOUT_RX_CAPACITY (512u * 1024u)
#define OTA_LAYOUT_IMAGE_MAX (OTA_LAYOUT_RX_CAPACITY - 64u)
#define OTA_LAYOUT_SLOT_BASE 0x400000u
#define OTA_LAYOUT_SLOT_SIZE 0x400000u
#define OTA_LAYOUT_BACKUP_HEADER 0x1000000u
#define OTA_LAYOUT_BACKUP_DATA 0x1001000u
#define OTA_LAYOUT_BACKUP_MAX 0x300000u
#define OTA_LAYOUT_ACTIVE_END 0x400000u
#define OTA_LAYOUT_AGENT 0x1400000u
#define OTA_LAYOUT_AGENT_SIZE 0x400000u
#endif

#endif
